// Phase 2C: the backend's real-tool toolbox (backend/app/commands/registry.py)
// in the order the learning progression uses them — understand the device
// (esptool.py -> strings -> grep), then reach it over the network or the
// MQTT protocol. `mqtt-explorer` was removed with Phase 2C: it was never a
// real tool, and its topic-browsing role is covered by `mosquitto_sub`.
const TOOLS = [
  {
    id: 'esptool',
    name: 'esptool.py',
    action: 'extract',
    // 64 KiB from the app-partition offset (0x10000), NOT the full 4 MiB
    // flash: a whole-flash read is minutes long and dumps the bootloader,
    // ESP-IDF/Arduino libraries, the second OTA slot and SPIFFS, which is
    // what buries the handful of config strings this exercise wants. The
    // app image (where the sketch's own string literals live) starts at
    // 0x10000; a 64 KiB window there is a fast, readable slice.
    command: 'esptool.py read_flash 0x10000 0x10000 firmware.bin',
  },
  { id: 'strings', name: 'strings', action: 'inspect', command: 'strings -n 8 firmware.bin' },
  { id: 'grep', name: 'grep', action: 'search', command: 'grep mqtt firmware.bin' },
  { id: 'nmap', name: 'nmap', action: 'scan', command: 'nmap' },
  { id: 'sub', name: 'mosquitto_sub', action: 'listen', command: 'mosquitto_sub' },
  { id: 'pub', name: 'mosquitto_pub', action: 'publish', command: 'mosquitto_pub' },
]

function nowStamp() {
  return new Date().toLocaleTimeString('en-GB', { hour12: false })
}

// Activity Log timestamp for one backend event.
//
// Phase 2B: `occurred_at` is generated by the SERVER (backend/app/events/
// clock.py) and arrives on the `event` frame as ISO 8601 UTC. It is the
// exact stamp the durable event log holds, so preferring it means what a
// student sees here and what a professor later sees in their performance
// record are the same row — the browser's own clock can be wrong, in another
// timezone, or simply changed, and is not evidence.
//
// Rendered in the viewer's local time, because a student reading their own
// session wants wall-clock time, not UTC. The `nowStamp()` fallback covers
// only an older backend that does not send the field (protocol < 5) or an
// unparseable value; it is never the preferred path.
function eventStamp(occurredAt) {
  if (!occurredAt) return nowStamp()
  const parsed = new Date(occurredAt)
  if (Number.isNaN(parsed.getTime())) return nowStamp()
  return parsed.toLocaleTimeString('en-GB', { hour12: false })
}

// True-color ANSI escapes in the design system's danger red, used only for
// frontend-injected notices (protocol errors) — never for backend `output`
// text, which is written verbatim.
const ANSI_ERR = '\x1b[38;2;255;123;123m'
const ANSI_RESET = '\x1b[0m'

// "Near enough to the bottom that a new Activity Log entry should still
// auto-scroll into view".
const LOG_AUTOSCROLL_THRESHOLD_PX = 32

const OBJECTIVE_ICON = {
  [OBJECTIVE_STATE.DONE]: 'status-done',
  [OBJECTIVE_STATE.PARTIAL]: 'status-partial',
  [OBJECTIVE_STATE.PENDING]: 'status-pending',
}

function Row({ label, children }) {
  return (
    <div className="kv-row">
      <dt>{label}</dt>
      <dd>{children}</dd>
    </div>
  )
}

// The TARGET DEVICE readout. The scenario owns the snapshot's shape, so this
// branches on which shape arrived, never on a panel id.
function TargetDevice({ scenarioState, panelName }) {
  if (!scenarioState) {
    return <p className="empty-line">No contact with the target yet — begin recon.</p>
  }
  if (!hasActivityTarget(scenarioState)) {
    // A foundation panel (its package defines no activity yet): the snapshot
    // carries no target/discovery skeleton, so say what it says and read
    // nothing else. See targetDeviceModel.js.
    return <p className="empty-line">{foundationSummary(scenarioState)}</p>
  }
  const { target, discovery } = scenarioState
  const attack = scenarioState.attack || {}
  const unknown = 'UNKNOWN — recover from firmware'
  return (
    <dl className="kv">
      {panelName ? <Row label="Panel">{panelName}</Row> : null}
      <Row label="Status">{String(target.device_status).toUpperCase()}</Row>
      {scenarioState.motor ? (
        // Smart Home MQTT Control (Panel 1, Phase 2E.1): the snapshot shape is
        // scenario-owned and genuinely different from the Environmental
        // target's (motor/broker_host vs environment/ip_address).
        <>
          <Row label="Broker">
            {discovery.broker_discovered ? `${target.broker_host}:${target.broker_port}` : unknown}
          </Row>
          <Row label="Command topic">{discovery.topic_discovered ? target.command_topic : unknown}</Row>
          {discovery.mqtt_observed ? (
            <Row label="Motor">
              {scenarioState.motor.running ? 'RUNNING' : 'STOPPED'}
              {attack.spoof_active ? ' (SPOOFED)' : ''}
            </Row>
          ) : null}
        </>
      ) : (
        <>
          <Row label="Broker">
            {discovery.broker_discovered ? `${target.ip_address}:${target.mqtt_port}` : unknown}
          </Row>
          <Row label="Topic">{discovery.topic_discovered ? target.mqtt_topic : unknown}</Row>
          {discovery.mqtt_observed ? (
            <Row label="Telemetry">
              {scenarioState.environment.temperature}°C
              {attack.spoof_active ? ' (SPOOFED)' : ''}
            </Row>
          ) : null}
        </>
      )}
    </dl>
  )
}

export default function HackMode({ onBack, onBuild, onMenu, participantId }) {
  const termRef = useRef(null)
  const inputBufferRef = useRef('')

  // Whether the backend's generic output pager (backend/app/pager.py) is
  // currently holding this terminal's input, mirrored in `promptStateRef`
  // below via `applyPromptFrame` every time a `pager_start`/`pager_end`
  // action frame arrives (see the `onAction` handler below). While true,
  // `handleTerminalInput` stops buffering keystrokes into a command line
  // and instead forwards each one to the backend immediately, exactly as a
  // real pager reacts the instant Space/q is pressed rather than after
  // Enter — see that function for the full explanation. A ref, not state:
  // it only ever needs to be read inside the next keystroke's event
  // handler, never to drive a re-render.
  const pagerActiveRef = useRef(false)

  // Drives the terminal's own `cybertrainer@cybertrainer: -$ ` prompt (see
  // src/hackTerminal/terminalPromptModel.js): a ref, for the same reason
  // `pagerActiveRef` above is one — it only ever needs to be read/updated
  // inside a socket callback or a keystroke handler, never to drive a
  // re-render.
  const promptStateRef = useRef(initialPromptState())

  // Scenario events and the scenario state snapshot drive the Activity Log,
  // Objectives and Target Device panels below. Both are local to this
  // component (not lifted to App.jsx): HackMode already fully unmounts on
  // every "back to menu" -> "hack" round trip (App.jsx has no stable key
  // keeping it alive across screen changes), which is what resets this state
  // for a new session — no extra teardown code needed.
  const [scenarioEvents, setScenarioEvents] = useState([])
  const [scenarioState, setScenarioState] = useState(null)

  // Shared ESP32 presence, from backend/app/hardware/ — the SAME
  // process-wide device state Build Mode reads, not a Hack-Mode-owned
  // device and not a second detection path. Held apart from
  // `scenarioState` on purpose: the scenario is the simulated target a
  // student attacks, this is the physical board plugged into the machine,
  // and conflating them is exactly what would let hardware noise leak into
  // the Activity Log or the Target Device panel.
  const [hardware, setHardware] = useState(UNKNOWN_HARDWARE)

  // 'idle' | 'copied' | 'failed' — feedback for the Copy output button.
  const [copyState, setCopyState] = useState('idle')
  const copyTimerRef = useRef(null)

  // Writes a chunk of backend-authored text to the terminal verbatim — no
  // prefix, no reformatting. Terminal-rendered timestamps were removed
  // (the backend still records them exactly as before; see
  // backend/app/events/ and CLAUDE.md) in favour of the fixed shell prompt
  // below, which is drawn as its own separate write, never woven into
  // output text.
  function writeOutput(text) {
    if (!text) return
    termRef.current?.write(text)
  }

  // Applies one prompt-relevant signal (see
  // src/hackTerminal/terminalPromptModel.js) to `promptStateRef`, drawing
  // the (Pi-style colored) prompt when it says to. This is the one place
  // `promptStateRef` is written, so every caller below funnels through it
  // rather than touching `pagerActiveRef`/the terminal directly.
  function applyPrompt(frame) {
    const { state, showPrompt } = applyPromptFrame(promptStateRef.current, frame)
    promptStateRef.current = state
    pagerActiveRef.current = state.pagerActive
    if (showPrompt) termRef.current?.write(PROMPT_DISPLAY)
  }

  const { status, sendInput, sendResize, sendHardwareStatus } = useHackSocket({
    participantId,
    onSession: () => {
      // A `session` frame only ever arrives once per connection (right after
      // accept — see backend/app/websocket.py), so this is defensive rather
      // than something that fires mid-session: it guarantees a brand new
      // session can never inherit a stale event/state carried over in this
      // component's own state.
      setScenarioEvents([])
      setScenarioState(null)
    },
    // The backend's welcome banner arrives as an ordinary `output` frame
    // like any other, so it needs no special case: `applyPrompt` draws the
    // very first prompt right after it, the same way it draws every prompt
    // that follows a command's output.
    onOutput: (data) => {
      writeOutput(data)
      applyPrompt({ type: 'output' })
    },
    onAction: (action) => {
      if (action === 'clear') termRef.current?.clear()
      applyPrompt({ type: 'action', action })
    },
    onError: (message) => {
      writeOutput(`${ANSI_ERR}[protocol error] ${message}${ANSI_RESET}\r\n`)
      applyPrompt({ type: 'output' })
    },
    onEvent: (message) => {
      setScenarioEvents((events) => {
        // Guard against the exact same frame landing twice (e.g. a stray
        // redelivery), not against the backend legitimately re-emitting the
        // same event type later for a distinct occurrence (a rejected spoof
        // attempt, for instance, can happen more than once and each is real
        // activity worth logging).
        //
        // Phase 2B made that distinction exact. `sequence` is the event's
        // position in the backend's own per-session log, so two rows are the
        // same occurrence precisely when they share it — no longer inferred
        // from type+data, which could not tell two identical rejected spoofs
        // apart. The type+data heuristic remains as the fallback for a
        // backend that does not send `sequence` (protocol < 5).
        const last = events[events.length - 1]
        if (last) {
          if (message.sequence != null && last.sequence != null) {
            if (last.sequence === message.sequence) return events
          } else if (
            last.event === message.event &&
            JSON.stringify(last.data) === JSON.stringify(message.data)
          ) {
            return events
          }
        }
        return [
          ...events,
          {
            event: message.event,
            data: message.data,
            sequence: message.sequence ?? null,
            at: eventStamp(message.occurred_at),
          },
        ]
      })
    },
    onState: (data) => setScenarioState(data),
    // SILENT BY CONSTRUCTION — Phase 1's hard requirement. This handler
    // does one thing: swap the hardware badge's data. It deliberately does
    // not call `writeOutput` (nothing reaches xterm.js — no "ESP32
    // CONNECTED", no "NO ESP32 DETECTED", no line at all), does not touch
    // `scenarioEvents` (nothing reaches the Activity Log), and does not
    // touch `scenarioState` (no exploit/discovery flag moves). A board
    // being plugged in is not something the student did.
    onHardware: (data) => setHardware(data || UNKNOWN_HARDWARE),
  })

  // Keeps the badge truthful as the board is plugged in, pulled out, or
  // reconnected while Hack Mode stays open — no page refresh, and no
  // second detection path, since every poll resolves to the one shared
  // `device_monitor` the backend also answers Build Mode from. Re-checks
  // immediately on (re)connect so a freshly opened screen never shows
  // "CHECKING…" for a whole interval.
  useEffect(() => {
    if (status !== CONNECTION_STATUS.CONNECTED) return undefined
    sendHardwareStatus()
    const id = setInterval(sendHardwareStatus, HARDWARE_POLL_INTERVAL_MS)
    return () => clearInterval(id)
  }, [status, sendHardwareStatus])

  // When the socket itself isn't open, nothing about `hardware` can be
  // trusted (it's whatever was last pushed, possibly never), so the header
  // falls back to "nothing known" rather than reporting a stale board as
  // still attached. The socket's own state is never *shown* — it is
  // diagnostics, and the header reports the ESP32, not the transport.
  const device = status === CONNECTION_STATUS.CONNECTED ? hardware : UNKNOWN_HARDWARE
  const port = usbRepresentations(device)[0]

  const objectives = deriveObjectives(scenarioState)
  const progress = objectiveProgress(objectives.items)

  // Activity Log: a new entry scrolls into view only if the reader was already
  // at/near the bottom.
  const logRef = useRef(null)
  const logNearBottomRef = useRef(true)
  useEffect(() => {
    const el = logRef.current
    if (el && logNearBottomRef.current) el.scrollTop = el.scrollHeight
  }, [scenarioEvents])

  useEffect(
    () => () => {
      if (copyTimerRef.current) clearTimeout(copyTimerRef.current)
    },
    [],
  )

  // The single path a completed command line takes to the backend, whether
  // it came from the terminal's own Enter key or a tool button below —
  // there is no second, mock execution path.
  function submitCommand(line) {
    sendInput(line)
  }

  function runTool(tool) {
    // A tool button is a shortcut for typing a command line, so it makes no
    // sense while a pager has the terminal's input — the backend would just
    // ignore it as an unrecognised pager keystroke (see
    // backend/app/pager.py's `PagerAction.from_input`), leaving a command
    // echoed on screen that never ran. Page through or quit (q/Ctrl+C) first.
    if (pagerActiveRef.current) return
    // Tool buttons must send exactly what typing the command and pressing
    // Enter would: this locally echoes it right after the prompt already on
    // screen (mirroring the character-by-character echo `handleTerminalInput`
    // does for real typing) and then sends it through the same
    // `submitCommand` — one echo mechanism, one submission path.
    writeOutput(`${tool.command}\r\n`)
    submitCommand(tool.command)
  }

  // Local terminal line discipline: the browser still owns character echo,
  // backspace, and Ctrl+C. Only a completed line is ever sent onward — see
  // backend/app/websocket.py, which expects exactly one `input` frame per
  // completed command line, never individual keystrokes. `PROMPT_TEXT` is
  // already on screen by the time the student types the first character of
  // a line (drawn by `applyPrompt`, above), so a typed character is just
  // echoed onto that same line — no per-keystroke prefixing logic needed.
  //
  // A blank Enter (nothing typed) and Ctrl+C never reach the backend at all
  // — the terminal is instantly ready again with no round trip, so each
  // draws the next prompt itself via `applyPrompt({ type: 'local-ready' })`
  // rather than waiting for an `output` frame that will never arrive for
  // this "command".
  //
  // PAGER MODE is the one exception, and it takes over before any of that
  // line-discipline logic runs. While `pagerActiveRef.current` is true (see
  // the `pager_start`/`pager_end` cases in `onAction` above), the backend's
  // pager (backend/app/pager.py) is waiting for exactly one raw keystroke —
  // Enter, Space, q, or Ctrl+C — and needs it the instant it's pressed, not
  // after a buffered line's Enter. So every character xterm hands back is
  // forwarded to the backend immediately and unbuffered: not appended to
  // `inputBufferRef`, not locally echoed (the backend's own reply — the next
  // page, or the line ending that closes the pager — is the only thing that
  // reaches the screen), and never treated as a command line. This is also
  // why Ctrl+C behaves differently here than in the branch below: normally
  // it only clears the local buffer and never reaches the backend at all,
  // but a pager needs a real Ctrl+C keystroke to be able to exit on it.
  function handleTerminalInput(data) {
    if (pagerActiveRef.current) {
      for (const ch of data) sendInput(ch)
      return
    }
    const term = termRef.current
    if (!term) return
    for (const ch of data) {
      if (ch === '\r') {
        term.write('\r\n')
        const cmd = inputBufferRef.current.trim()
        inputBufferRef.current = ''
        if (cmd) {
          submitCommand(cmd)
        } else {
          applyPrompt({ type: 'local-ready' })
        }
      } else if (ch === '\x7f') {
        if (inputBufferRef.current.length > 0) {
          inputBufferRef.current = inputBufferRef.current.slice(0, -1)
          term.write('\b \b')
        }
      } else if (ch === '\x03') {
        inputBufferRef.current = ''
        term.write('^C\r\n')
        applyPrompt({ type: 'local-ready' })
      } else if (ch >= ' ') {
        inputBufferRef.current += ch
        term.write(ch)
      }
    }
  }

  function handleTerminalResize({ cols, rows }) {
    sendResize(cols, rows)
  }

  // Display-only: copies what is already on screen and clears the on-screen
  // scrollback. Neither sends a frame or reaches the backend, and the clear
  // keeps the current prompt line (and anything typed on it) exactly as the
  // backend's own `clear` command does.
  async function copyOutput() {
    const copied = await copyToClipboard(termRef.current?.getText() ?? '')
    setCopyState(copied ? 'copied' : 'failed')
    if (copyTimerRef.current) clearTimeout(copyTimerRef.current)
    copyTimerRef.current = setTimeout(() => setCopyState('idle'), 1800)
  }

  function clearOutput() {
    termRef.current?.clear()
  }

  return (
    <div className="screen screen-fixed">
      <AppHeader
        title="Hack Mode"
        badge="Authorized lab only"
        onMenu={onMenu}
        meta={
          objectives.kind === 'list' ? (
            <>
              <span>
                Objectives {progress.done} / {progress.total}
              </span>
              <div
                className="progress hack-progress"
                role="progressbar"
                aria-label="Objectives completed"
                aria-valuenow={progress.done}
                aria-valuemin={0}
                aria-valuemax={progress.total}
              >
                <span style={{ width: `${(progress.done / progress.total) * 100}%` }} />
              </div>
            </>
          ) : null
        }
      />

      <main className="screen-body hack-body">
        <aside className="hack-col hack-col-left">
          <section className="card hack-card" aria-label="Objectives">
            <h2 className="hack-card-title">Objectives</h2>
            {objectives.kind === 'list' ? (
              <ul className="objectives">
                {objectives.items.map((item) => (
                  <li key={item.id} className={`objective is-${item.state}`}>
                    <Icon name={OBJECTIVE_ICON[item.state]} size={14} />
                    <span>{item.label}</span>
                    <span className="sr-only">
                      {item.state === OBJECTIVE_STATE.DONE
                        ? ' — complete'
                        : item.state === OBJECTIVE_STATE.PARTIAL
                          ? ' — in progress'
                          : ' — not started'}
                    </span>
                  </li>
                ))}
              </ul>
            ) : objectives.kind === 'none' ? (
              <p className="empty-line">
                <Icon name="info" size={14} /> No training objectives are defined for this panel yet.
              </p>
            ) : (
              <p className="empty-line">Objectives appear once the target reports its state.</p>
            )}
          </section>

          <section className="card hack-card is-grow" aria-label="Activity log">
            <h2 className="hack-card-title">Activity Log</h2>
            <ul
              className="activity-log"
              ref={logRef}
              onScroll={(e) => {
                const el = e.currentTarget
                logNearBottomRef.current =
                  el.scrollHeight - el.scrollTop - el.clientHeight < LOG_AUTOSCROLL_THRESHOLD_PX
              }}
            >
              {scenarioEvents.length === 0 ? (
                <li className="empty-line">No activity yet — run a command to begin.</li>
              ) : (
                scenarioEvents.map((entry, i) => (
                  <li key={i}>
                    <span className="log-time">{entry.at}</span>
                    <span>{hackEventLabel(entry.event)}</span>
                  </li>
                ))
              )}
            </ul>
          </section>

          <button type="button" className="btn btn-block" onClick={onBack}>
            <Icon name="arrow-left" size={14} />
            Back to menu
          </button>
        </aside>

        <section className="card hack-terminal" aria-label="Terminal">
          <div className="terminal-bar">
            <span className="terminal-title">
              <Icon name="terminal" size={16} />
              Terminal
              {port ? <span className="terminal-port">{port}</span> : null}
            </span>
            <div className="terminal-actions">
              <button
                type="button"
                className="icon-btn is-quiet is-sm"
                aria-label="Copy output"
                title="Copy the terminal output"
                onClick={copyOutput}
              >
                <Icon name={copyState === 'copied' ? 'status-done' : 'copy'} size={16} />
              </button>
              <button
                type="button"
                className="icon-btn is-quiet is-sm"
                aria-label="Clear terminal"
                title="Clear the terminal screen"
                onClick={clearOutput}
              >
                <Icon name="trash" size={16} />
              </button>
              <span className="sr-only" role="status">
                {copyState === 'copied' ? 'Output copied' : copyState === 'failed' ? 'Copy failed' : ''}
              </span>
            </div>
          </div>
          <div className="terminal-screen">
            <HackTerminal ref={termRef} onInput={handleTerminalInput} onResize={handleTerminalResize} />
          </div>
          <div className="terminal-foot">
            <span>Commands run only through the trainer&apos;s real-tool toolbox. Type help to list them.</span>
          </div>
        </section>

        <aside className="hack-col hack-col-right">
          <section className="card hack-card" aria-label="Toolbox">
            <h2 className="hack-card-title">Toolbox</h2>
            <div className="tool-grid">
              {TOOLS.map((t) => (
                <button
                  key={t.id}
                  type="button"
                  className="tool-chip"
                  title={`${t.action}: runs ${t.command}`}
                  aria-label={`${t.name} — ${t.action}`}
                  onClick={() => runTool(t)}
                >
                  {t.name}
                </button>
              ))}
            </div>
          </section>

          <section className="card hack-card" aria-label="Target device">
            <h2 className="hack-card-title">Target Device</h2>
            <TargetDevice scenarioState={scenarioState} panelName={device.panel} />
          </section>

          <button type="button" className="btn btn-primary btn-block hack-proceed" onClick={onBuild}>
            Proceed to Build Mode
            <Icon name="arrow-right" size={16} />
          </button>
        </aside>
      </main>

      <StatusBar>
        {/* The uniform panel/hardware readout. Identical component and
            identical shared device state in Build Mode — the mode name in the
            top bar is the only difference between the two screens. */}
        <HardwareHeaderStatus hardware={device} />
      </StatusBar>
    </div>
  )
}
