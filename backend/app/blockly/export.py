"""Serialises the master catalog for the frontend.

The Python catalog is the single source of truth. The frontend never restates
category or block metadata by hand; it imports the JavaScript module
`render_frontend_module` produces, checked in at `FRONTEND_MODULE_PATH` and
regenerated with `backend/scripts/export_blockly_catalog.py`. A test compares
the checked-in file with a fresh render so the two cannot drift apart.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.blockly.catalog import BlockCatalog
from app.blockly.models import BlockDefinition
from app.blockly.toolbox import build_toolbox

#: `<repo>/src/blockly/catalog/masterCatalog.generated.js`, relative to this file.
FRONTEND_MODULE_PATH = (
    Path(__file__).resolve().parents[3] / "src" / "blockly" / "catalog" / "masterCatalog.generated.js"
)

_HEADER = (
    "// GENERATED by backend/scripts/export_blockly_catalog.py from app/blockly/ -- do not edit by hand.\n"
    "// The Python master block catalog is the source of truth; regenerate after changing it.\n"
)


def _block_to_dict(block: BlockDefinition) -> dict[str, Any]:
    return {
        "id": block.block_id,
        "categoryId": block.category_id,
        "displayName": block.display_name,
        "description": block.description,
        "kind": block.kind.value,
        "semanticOperation": block.semantic_operation,
        "inputs": [
            {"name": item.name, "valueType": item.value_type.value, "description": item.description}
            for item in block.inputs
        ],
        "output": block.output.value if block.output is not None else None,
        "dependencies": list(block.dependencies),
        "capabilities": [capability.value for capability in block.capabilities],
        "status": block.status.value,
        "blocklyType": block.blockly_type,
        "generatorId": block.generator_id,
    }


def catalog_to_dict(catalog: BlockCatalog) -> dict[str, Any]:
    """The catalog as plain JSON-safe data, camelCase for the frontend."""
    return {
        "categories": [
            {
                "id": category.category_id,
                "displayName": category.display_name,
                "description": category.description,
                "group": category.group.value,
                "hue": category.hue,
                "optional": category.optional,
            }
            for category in catalog.categories
        ],
        "blocks": [_block_to_dict(block) for block in catalog.blocks],
    }


def render_frontend_module(catalog: BlockCatalog) -> str:
    """The exact text of the generated frontend module (LF line endings)."""
    exports = (
        ("MASTER_CATALOG", catalog_to_dict(catalog)),
        ("FULL_TOOLBOX", build_toolbox(catalog)),
        ("POPULATED_TOOLBOX", build_toolbox(catalog, hide_empty_categories=True)),
    )
    body = "".join(
        f"\nexport const {name} = {json.dumps(value, indent=2)}\n" for name, value in exports
    )
    return _HEADER + body
